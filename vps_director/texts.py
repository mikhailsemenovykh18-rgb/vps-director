# More languages: vps_director/lang/<code>.py holds TEXTS with the translated keys; anything a translation
# lacks comes from English, so a new or partial language never breaks a message.
EXTRA_LANGS = ("es", "de", "fr", "pt")


def _with_fallback(code):
    import importlib
    try:
        extra = importlib.import_module("vps_director.lang." + code).TEXTS
    except ImportError:
        extra = {}
    merged = dict(TEXTS["en"])
    merged["cmds"] = dict(TEXTS["en"]["cmds"], **extra.get("cmds", {}))
    merged.update({k: v for k, v in extra.items() if k != "cmds"})
    return merged


for _code in EXTRA_LANGS:
    TEXTS[_code] = _with_fallback(_code)
