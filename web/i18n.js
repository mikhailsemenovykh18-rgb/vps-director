  function pluralIndex(lang, n) {
    n = Math.abs(n);
    if (lang === "ru") {
      var d = n % 10, h = n % 100;
      if (d === 1 && h !== 11) return 0;
      if (d >= 2 && d <= 4 && (h < 12 || h > 14)) return 1;
      return 2;
    }
    if (lang === "fr" || lang === "pt") return n < 2 ? 0 : 1;
    return n === 1 ? 0 : 1;
  }

  function make(lang) {
    lang = STRINGS[lang] ? lang : "en";
    function t(key, vars) {
      var s = STRINGS[lang][key];
      if (s === undefined) s = STRINGS.en[key];
      if (s === undefined) return key;
      if (Array.isArray(s)) {
        var forms = s;
        s = forms[Math.min(pluralIndex(lang, (vars && vars.n) || 0), forms.length - 1)];
      }
      return s.replace(/\{(\w+)\}/g, function (m, k) {
        return vars && vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : m;
      });
    }
    t.lang = lang;
    return t;
  }

